// Builds the MySQL baseline migration from prisma/mysql/schema.prisma (reproducible):
//   node scripts/mysql-schema.mjs && node scripts/mysql-migration.mjs
//   1. prisma migrate diff (empty → schema)          tables, indexes, foreign keys
//   2. JSON column defaults                          Prisma does not emit dbgenerated() defaults for JSON
//   3. scripts/mysql-seed-sql.ts                     CHECK constraints + features, plans, platform settings
// Writes prisma/mysql/migrations/20261007000000_mysql_baseline/migration.sql
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const schemaPath = join(root, "prisma", "mysql", "schema.prisma");
const dir = join(root, "prisma", "mysql", "migrations", "20261007000000_mysql_baseline");
const prisma = join(root, "node_modules", "prisma", "build", "index.js");
const env = { ...process.env, DATABASE_URL: "mysql://offline:offline@localhost:3306/offline" }; // not contacted

let sql = execFileSync(process.execPath, [prisma, "migrate", "diff", "--from-empty", "--to-schema-datamodel", schemaPath, "--script"], { env, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });

// JSON defaults from the schema: field → expression, per model
const schema = readFileSync(schemaPath, "utf8").replace(/\r\n/g, "\n");
let model = null;
let patched = 0;
for (const line of schema.split("\n")) {
  const m = /^model (\w+) \{/.exec(line);
  if (m) model = m[1];
  const f = /^\s+(\w+)\s+Json\s+@default\(dbgenerated\("(.*)"\)\)/.exec(line);
  if (!model || !f) continue;
  const [, field, expr] = f;
  const table = new RegExp("(CREATE TABLE `" + model + "` \\([\\s\\S]*?`" + field + "` JSON NOT NULL)(,)");
  if (!table.test(sql)) throw new Error(`JSON column ${model}.${field} not found in the generated SQL`);
  sql = sql.replace(table, `$1 DEFAULT ${expr}$2`);
  patched++;
}

const seed = execFileSync(process.execPath, [join(root, "node_modules", "tsx", "dist", "cli.mjs"), join(root, "scripts", "mysql-seed-sql.ts")], { encoding: "utf8" });
const header = "-- MySQL 8.0.16+ / MariaDB 10.6+ baseline for বিজয় লেনদেন (generated by scripts/mysql-migration.mjs).\n-- Equivalent to all PostgreSQL migrations up to 20261005300000_saas_inventory_payment_status.\n\n";
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, "migration.sql"), header + sql.trimEnd() + "\n" + seed);
writeFileSync(join(root, "prisma", "mysql", "migrations", "migration_lock.toml"), '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "mysql"\n');
console.log(`baseline written (${patched} JSON defaults)`);
