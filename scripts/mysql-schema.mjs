// Generates prisma/mysql/schema.prisma (MySQL 8 / MariaDB 10.6+) from prisma/schema.prisma (PostgreSQL).
// The PostgreSQL schema stays the single source of truth; run after every schema change:
//   node scripts/mysql-schema.mjs            (write)
//   node scripts/mysql-schema.mjs --check    (fail if the committed MySQL schema is out of date)
//
// Conversions
//   provider postgresql → mysql
//   scalar lists (String[] / Int[])  → Json, with the same default as a JSON_ARRAY(...) expression
//   String fields that are not part of a key / index / relation → @db.Text (MySQL VARCHAR is 191 chars);
//     very large ones (logo data URL) → @db.MediumText; e-mail addresses → @db.VarChar(255)
// Everything else (models, enums, relations, Decimal precision, indexes) is identical, so the
// generated Prisma Client has the same API on both databases (lists are read via src/lib/dialect.ts).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const root = process.cwd();
const src = readFileSync(join(root, "prisma", "schema.prisma"), "utf8").replace(/\r\n/g, "\n");
const target = join(root, "prisma", "mysql", "schema.prisma");

const MEDIUM_TEXT = new Set(["Business.logo"]);
const lines = src.split("\n");

// 1. which fields of each model are keys / indexed / relation scalars (must stay VARCHAR)
const keyed = new Map(); // model → Set(field)
let model = null;
for (const line of lines) {
  const m = /^model (\w+) \{/.exec(line);
  if (m) { model = m[1]; keyed.set(model, new Set()); continue; }
  if (line.startsWith("}")) { model = null; continue; }
  if (!model) continue;
  const set = keyed.get(model);
  const field = /^\s+(\w+)\s+\S+/.exec(line)?.[1];
  if (field && /@id\b|@unique\b/.test(line)) set.add(field);
  for (const block of line.matchAll(/@@(?:id|unique|index)\(\s*(?:fields:\s*)?\[([^\]]*)\]/g)) {
    for (const f of block[1].split(",")) set.add(f.trim().replace(/\(.*$/, ""));
  }
  for (const rel of line.matchAll(/(?:fields|references):\s*\[([^\]]*)\]/g)) {
    for (const f of rel[1].split(",")) set.add(f.trim());
  }
}
// referenced columns of other models (e.g. Feature.key referenced by PlanFeature)
for (const line of lines) {
  const r = /^\s+\w+\s+(\w+)\??\s+@relation\(.*references:\s*\[([^\]]*)\]/.exec(line);
  if (r && keyed.has(r[1])) for (const f of r[2].split(",")) keyed.get(r[1]).add(f.trim());
}

// 2. rewrite
const out = [];
model = null;
const sqlList = (items) => items.map((v) => (/^-?\d+(\.\d+)?$/.test(v) ? v : `'${v.replace(/^"|"$/g, "").replace(/'/g, "''")}'`)).join(", ");
for (const line of lines) {
  const m = /^model (\w+) \{/.exec(line);
  if (m) model = m[1];
  if (line.startsWith("}")) model = null;
  if (/^\s*provider\s*=\s*"postgresql"/.test(line)) { out.push(line.replace('"postgresql"', '"mysql"')); continue; }
  if (!model) { out.push(line); continue; }

  // scalar list → Json
  const list = /^(\s+)(\w+)(\s+)(String|Int)\[\](\s*)(.*)$/.exec(line);
  if (list) {
    const [, ind, name, sp, , sp2, rest] = list;
    const def = /@default\(\[(.*?)\]\)/.exec(rest);
    const items = def ? def[1].split(",").map((s) => s.trim()).filter(Boolean) : null;
    const attr = items ? `@default(dbgenerated("(json_array(${sqlList(items)}))"))` : "";
    const restNoDefault = rest.replace(/@default\(\[.*?\]\)\s*/, "");
    out.push(`${ind}${name}${sp}Json${" ".repeat(Math.max(1, "String[]".length - 4 + sp2.length))}${[attr, restNoDefault].filter(Boolean).join(" ")}`.replace(/\s+$/, ""));
    continue;
  }

  // String columns: keys stay VARCHAR(191); free text → TEXT
  const str = /^(\s+)(\w+)(\s+)(String\??)(\s+.*)?$/.exec(line);
  if (str && !/@db\./.test(line)) {
    const [, ind, name, sp, type, restRaw = ""] = str;
    const key = keyed.get(model)?.has(name);
    let native = null;
    if (/^email$/i.test(name)) native = "@db.VarChar(255)";
    else if (MEDIUM_TEXT.has(`${model}.${name}`)) native = "@db.MediumText";
    else if (!key && !/@default\(/.test(restRaw)) native = "@db.Text";
    else if (!key && /@default\(/.test(restRaw)) native = "@db.VarChar(191)"; // TEXT columns cannot have literal defaults on older MySQL
    if (native) {
      const comment = restRaw.indexOf("//");
      const attrs = comment >= 0 ? restRaw.slice(0, comment).trimEnd() : restRaw.trimEnd();
      const tail = comment >= 0 ? " " + restRaw.slice(comment) : "";
      out.push(`${ind}${name}${sp}${type}${attrs ? attrs : ""} ${native}${tail}`.replace(/\s+$/, ""));
      continue;
    }
  }
  out.push(line);
}

const header = `// GENERATED by scripts/mysql-schema.mjs from prisma/schema.prisma — do not edit by hand.\n// MySQL 8.0.16+ / MariaDB 10.6+ variant for cPanel hosting (see docs/MYSQL-MIGRATION-PLAN.md).\n\n`;
// normalise with prisma format (column alignment) so --check compares like with like
const tmp = join(tmpdir(), `bl-mysql-schema-${process.pid}.prisma`);
writeFileSync(tmp, header + out.join("\n"));
execFileSync(process.execPath, [join(root, "node_modules", "prisma", "build", "index.js"), "format", "--schema", tmp], { stdio: "ignore" });
const result = readFileSync(tmp, "utf8").replace(/\r\n/g, "\n");
rmSync(tmp, { force: true });
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing */ }
  if (current !== result) {
    console.error("prisma/mysql/schema.prisma is out of date — run: node scripts/mysql-schema.mjs");
    process.exit(1);
  }
  console.log("prisma/mysql/schema.prisma is up to date");
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, result);
  console.log(`wrote ${target}`);
}
