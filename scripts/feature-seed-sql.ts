// Prints the INSERT statements that seed the feature catalogue from src/lib/features.ts.
// Used to write the seed part of the feature-management migration:
//   npx tsx scripts/feature-seed-sql.ts
// (At runtime ensureFeatureCatalog() keeps the table in sync with the registry as well.)
import { FEATURES, type FeatureDef } from "../src/lib/features";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines: string[] = ["-- Seed: feature catalogue and module permissions (generated by scripts/feature-seed-sql.ts)"];
(FEATURES as readonly FeatureDef[]).forEach((f, i) => {
  lines.push(
    `INSERT INTO "Feature" ("key", "nameBn", "nameEn", "descriptionBn", "descriptionEn", "icon", "tier", "status", "defaultEnabled", "sortOrder", "updatedAt") VALUES (${[
      q(f.key), q(f.nameBn), q(f.nameEn), q(f.descriptionBn), q(f.descriptionEn), q(f.icon), `'${f.tier}'`, `'${f.status}'`, String(f.defaultEnabled), String(i * 10), "CURRENT_TIMESTAMP",
    ].join(", ")}) ON CONFLICT ("key") DO NOTHING;`,
  );
  for (const [action, perms] of Object.entries(f.permissions)) {
    for (const p of perms ?? []) {
      lines.push(
        `INSERT INTO "FeaturePermission" ("id", "featureKey", "action", "permission", "owned") VALUES (${q(`fp_${f.key}_${action}_${p}`.toLowerCase().replace(/[^a-z0-9_]/g, "_"))}, ${q(f.key)}, ${q(action)}, ${q(p)}, ${(f.owns as readonly string[]).includes(p)}) ON CONFLICT DO NOTHING;`,
      );
    }
  }
});
console.log(lines.join("\n"));
