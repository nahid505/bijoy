// Prints the seed / backfill SQL of the SaaS migration (plans, plan features, platform settings,
// subscriptions for businesses that existed before subscriptions). Plans and prices are only
// INITIAL values — afterwards they are edited in the Super Admin panel (database), not in code.
//   npx tsx scripts/saas-seed-sql.ts
import { FEATURES, type FeatureDef } from "../src/lib/features";
import { PLANS } from "./plan-seed-data";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

const out: string[] = ["-- Seed: feature catalogue (new core modules), plans, platform settings (generated by scripts/saas-seed-sql.ts)"];
(FEATURES as readonly FeatureDef[]).forEach((f, i) => {
  out.push(
    `INSERT INTO "Feature" ("key", "nameBn", "nameEn", "descriptionBn", "descriptionEn", "icon", "tier", "status", "defaultEnabled", "sortOrder", "updatedAt") VALUES (${[q(f.key), q(f.nameBn), q(f.nameEn), q(f.descriptionBn), q(f.descriptionEn), q(f.icon), `'${f.tier}'`, `'${f.status}'`, String(f.defaultEnabled), String(i * 10), "CURRENT_TIMESTAMP"].join(", ")}) ON CONFLICT ("key") DO UPDATE SET "sortOrder" = EXCLUDED."sortOrder";`,
  );
});
PLANS.forEach((p, i) => {
  out.push(
    `INSERT INTO "Plan" ("id", "code", "nameBn", "nameEn", "descriptionBn", "descriptionEn", "priceMonthly", "priceYearly", "userLimit", "isActive", "isPublic", "sortOrder", "createdAt", "updatedAt") VALUES (${[q(p.id), q(p.code), q(p.nameBn), q(p.nameEn), q(p.descBn), q(p.descEn), p.monthly, p.yearly, p.users, "true", "true", i * 10, "CURRENT_TIMESTAMP", "CURRENT_TIMESTAMP"].join(", ")}) ON CONFLICT ("code") DO NOTHING;`,
  );
  for (const f of p.features) out.push(`INSERT INTO "PlanFeature" ("planId", "featureKey") VALUES (${q(p.id)}, ${q(f)}) ON CONFLICT DO NOTHING;`);
});
out.push(`INSERT INTO "PlatformSetting" ("id", "updatedAt") VALUES ('platform', CURRENT_TIMESTAMP) ON CONFLICT ("id") DO NOTHING;`);
out.push(
  "-- Backfill: businesses that existed before subscriptions keep every feature they use today:",
  "-- PREMIUM, active for one year from the upgrade (the super admin can change this per company).",
  `INSERT INTO "Subscription" ("id", "businessId", "planId", "status", "billingCycle", "startDate", "endDate", "autoRenew", "createdAt", "updatedAt")
SELECT 'sub_' || b."id", b."id", 'plan_premium', 'ACTIVE', 'YEARLY', date_trunc('day', CURRENT_TIMESTAMP), date_trunc('day', CURRENT_TIMESTAMP) + INTERVAL '365 days', false, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM "Business" b WHERE NOT EXISTS (SELECT 1 FROM "Subscription" s WHERE s."businessId" = b."id");`,
  `INSERT INTO "SubscriptionEvent" ("id", "businessId", "subscriptionId", "type", "toPlanCode", "toStatus", "note", "createdAt")
SELECT 'sev_' || s."id", s."businessId", s."id", 'MIGRATED', 'PREMIUM', 'ACTIVE', 'Existing business moved to subscriptions with a one-year Premium grant', CURRENT_TIMESTAMP FROM "Subscription" s
WHERE NOT EXISTS (SELECT 1 FROM "SubscriptionEvent" e WHERE e."subscriptionId" = s."id");`,
);
console.log(out.join("\n"));
